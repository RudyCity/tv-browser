export const MESSAGES = Object.freeze({ en: EN, id: ID });

function lookup(store, key) {
  return Object.hasOwn(store, key) ? store[key] : undefined;
}

function interpolate(template, params) {
  if (!params) return template;

  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, name) => {
    if (!Object.hasOwn(params, name)) return placeholder;
    const value = params[name];
    return value === null || value === undefined ? placeholder : String(value);
  });
}

export function normalizeLanguage(value) {
  const candidate = typeof value === "string" ? value.trim().toLowerCase() : "";
  return LANGUAGES.includes(candidate) ? candidate : DEFAULT_LANGUAGE;
}

export function translate(language, key, params) {
  const store = MESSAGES[normalizeLanguage(language)];
  const template = typeof key === "string"
    ? lookup(store, key) ?? lookup(MESSAGES[DEFAULT_LANGUAGE], key)
    : undefined;

  if (typeof template !== "string") {
    return key === null || key === undefined ? "" : String(key);
  }

  return interpolate(template, params);
}

export function listKeys(language) {
  return Object.keys(MESSAGES[normalizeLanguage(language)]).sort();
}
